-- Backfill existing analyzed dreams without making any AI calls.
with feature_map(entity_type, feature_key) as (
  values ('theme','themes'), ('symbol','symbols'), ('character','characters'), ('place','locations'),
         ('emotion','emotions'), ('transformation','transformations'), ('object','objects'), ('action','actions')
), extracted as (
  select d.user_id, m.entity_type, value as canonical_name,
    trim(regexp_replace(regexp_replace(lower(value), '[^a-z0-9[:space:]-]', ' ', 'g'), '[[:space:]]+', ' ', 'g')) as normalized_name
  from public.dreams d cross join feature_map m
  cross join lateral jsonb_array_elements_text(coalesce(d.feature_json -> m.feature_key, '[]'::jsonb)) value
  where d.user_id is not null and d.feature_json is not null
)
insert into public.dream_entities(user_id, entity_type, canonical_name, normalized_name)
select distinct user_id, entity_type, canonical_name, normalized_name from extracted where normalized_name <> ''
on conflict do nothing;

with feature_map(entity_type, feature_key) as (
  values ('theme','themes'), ('symbol','symbols'), ('character','characters'), ('place','locations'),
         ('emotion','emotions'), ('transformation','transformations'), ('object','objects'), ('action','actions')
), extracted as (
  select d.id as dream_id, d.user_id, d.feature_version, m.entity_type, value as surface_form,
    trim(regexp_replace(regexp_replace(lower(value), '[^a-z0-9[:space:]-]', ' ', 'g'), '[[:space:]]+', ' ', 'g')) as normalized_name
  from public.dreams d cross join feature_map m
  cross join lateral jsonb_array_elements_text(coalesce(d.feature_json -> m.feature_key, '[]'::jsonb)) value
  where d.user_id is not null and d.feature_json is not null
)
insert into public.dream_entity_mentions(user_id, dream_id, entity_id, surface_form, confidence, source_version)
select x.user_id, x.dream_id, e.id, x.surface_form, 'medium', coalesce(x.feature_version, 1)
from extracted x join public.dream_entities e
  on e.user_id=x.user_id and e.entity_type=x.entity_type and e.normalized_name=x.normalized_name
where x.normalized_name <> ''
on conflict (dream_id, entity_id) do nothing;
