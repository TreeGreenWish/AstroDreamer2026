using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Users delete own dream entities" on public.dream_entities;
create policy "Users delete own dream entities" on public.dream_entities for delete to authenticated
using ((select auth.uid()) = user_id);

